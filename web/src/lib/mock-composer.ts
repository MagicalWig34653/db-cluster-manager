// Development-only fixtures of the image composer endpoints, loaded through
// mock.ts (import.meta.env.DEV && VITE_MOCK=1). The catalog is a copy of
// internal/imagecompose/catalog.json (a Go test keeps both equal); the
// preview below is NOT the manager's generator: it only imitates the shape of
// the answer so the page can be developed and captured. Every generated text
// says MOCK. The UI shows the "MOCK DATA" banner while it is active.

import catalog from './mock-composer-catalog.json';
import type { ComposerCatalog, ComposerIssue, ComposerPreview, ComposerRecipe } from './api';

const cat = catalog as unknown as ComposerCatalog;
const json = (status: number, body: unknown) => new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } });
const fakeDigest = (s: string) => {
	let h = 0;
	for (const c of s) h = (h * 31 + c.charCodeAt(0)) >>> 0;
	return 'sha256:' + h.toString(16).padStart(8, '0').repeat(8);
};

function issuesOf(r: ComposerRecipe): ComposerIssue[] {
	const issues: ComposerIssue[] = [];
	if (!/^[A-Za-z0-9][A-Za-z0-9 ._-]{0,62}$/.test(r.name ?? '')) issues.push({ path: 'name', message: 'must be 1-63 characters of letters, digits, space, ".", "_" or "-" (mock check)' });
	if (!/^sha256:[0-9a-f]{64}$/.test(r.base?.digest ?? '')) issues.push({ path: 'base.digest', message: 'the base image must be pinned by digest (sha256:<64 hex>); floating tags are not built (mock check)' });
	for (const sel of r.components ?? []) {
		const comp = cat.components.find((c) => c.id === sel.id);
		if (!comp) {
			issues.push({ path: `components[${sel.id}]`, message: 'unknown component (mock check)' });
			continue;
		}
		for (const key of Object.keys(sel.settings ?? {})) {
			const f = comp.settings?.find((x) => x.key === key);
			if (!f) issues.push({ path: `components[${sel.id}].settings.${key}`, message: 'setting is not in the allow-list (mock check)' });
			else if (f.type === 'int' && (typeof sel.settings![key] !== 'number' || (sel.settings![key] as number) < (f.min ?? -Infinity) || (sel.settings![key] as number) > (f.max ?? Infinity)))
				issues.push({ path: `components[${sel.id}].settings.${key}`, message: `must be between ${f.min} and ${f.max} (mock check)` });
		}
	}
	return issues;
}

function previewOf(r: ComposerRecipe): ComposerPreview {
	const issues = issuesOf(r);
	const family = cat.distros.find((d) => d.id === r.base?.distro)?.family ?? 'alpine';
	const variants = cat.distros.flatMap((d) =>
		d.releases.map((rel) => {
			const problems: string[] = [];
			const versions: Record<string, string> = {};
			for (const sel of r.components ?? []) {
				const comp = cat.components.find((c) => c.id === sel.id);
				const avail = (comp?.versions ?? []).filter((v) => v.support.some((s) => s.distro === d.id && s.release === rel.id)).map((v) => v.version);
				if (avail.length === 0) problems.push(`${sel.id} is not available`);
				else {
					versions[sel.id] = avail[0];
					if (!avail.includes(sel.version)) problems.push(`${sel.id} ${sel.version} is not available (newest here: ${avail[0]})`);
				}
			}
			return { distro: d.id, release: rel.id, name: rel.name, compatible: problems.length === 0, problems, versions };
		})
	);
	if (issues.length > 0) return { valid: false, issues, variants };
	const packages = (r.components ?? []).flatMap((sel) => {
		const comp = cat.components.find((c) => c.id === sel.id)!;
		return (sel.features ?? []).flatMap((f) => (comp.features?.find((x) => x.id === f)?.packages[family] ?? []).map((name) => ({ component: sel.id, name })));
	});
	const dockerfile = `# MOCK: sample text, not generated by the manager\nFROM ${r.base.distro}:${r.base.release}@${r.base.digest}\n# components: ${(r.components ?? []).map((c) => c.id + ' ' + c.version).join(', ')}\nUSER 10001:10001\n`;
	const files = [{ path: 'nginx/nginx.conf', mode: 420, content: '# MOCK: sample text, not generated by the manager\nworker_processes auto;\n' }];
	return {
		valid: true,
		issues: [],
		variants,
		recipe: r,
		digest: fakeDigest(JSON.stringify(r)),
		role: 'web',
		baseImage: `${r.base.distro}:${r.base.release}@${r.base.digest}`,
		contextHash: fakeDigest(dockerfile),
		dockerfile,
		files,
		packages,
		modules: [],
		warnings: ['MOCK: sample warning. The real preview lists limits of the generated image here.'],
		notes: ['MOCK: sample note.']
	};
}

export function composerMock(method: string, path: string, body: any): Response | undefined {
	if (method === 'GET' && path === '/api/v1/image-composer/catalog') return json(200, cat);
	if (method === 'POST' && path === '/api/v1/image-composer/preview') return json(200, previewOf(body.recipe ?? {}));
	if (method === 'POST' && path === '/api/v1/image-composer/builds') {
		const pv = previewOf(body.recipe ?? {});
		if (!pv.valid || !body.target?.registry) return json(400, { error: 'bad_request' });
		const planDigest = fakeDigest(pv.digest + JSON.stringify(body.target));
		const dockerfile = pv.dockerfile ?? '';
		if (!body.approvalDigest) {
			return json(200, {
				plan: {
					specHash: pv.digest,
					contextHash: pv.contextHash,
					digest: planDigest,
					baseImage: pv.baseImage,
					platforms: body.recipe.platforms ?? ['linux/amd64'],
					reference: `registry.example.invalid:5000/${body.target.repository}:${body.target.tag}`,
					dockerfile,
					files: pv.files,
					steps: [
						{ order: 1, title: 'Generate build context', detail: 'MOCK' },
						{ order: 2, title: 'Build', detail: 'MOCK: nothing is built in the mock server' }
					],
					warnings: ['MOCK: sample plan'],
					explanation: 'MOCK: sample plan, nothing is built.'
				}
			});
		}
		if (body.approvalDigest !== planDigest) return json(409, { error: 'approval_mismatch' });
		return json(202, {
			job: {
				id: 'mock-ib-1',
				name: body.recipe.name,
				status: 'succeeded',
				source: 'composer',
				specHash: pv.digest,
				contextHash: pv.contextHash,
				planDigest,
				reference: `registry.example.invalid:5000/${body.target.repository}:${body.target.tag}`,
				sbom: { status: 'not_generated' },
				createdAt: new Date().toISOString()
			}
		});
	}
	return undefined;
}
