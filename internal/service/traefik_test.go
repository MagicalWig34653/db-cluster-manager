func TestTraefikValidateRefusals(t *testing.T) {
	cases := []struct {
		name string
		mut  func(*TraefikSpec)
		want string
	}{
		{"no entry points", func(s *TraefikSpec) { s.EntryPoints = nil }, "entry point"},
		{"unknown entry point", func(s *TraefikSpec) { s.Routers[0].EntryPoints = []string{"x"} }, "unknown entry point"},
		{"unknown service", func(s *TraefikSpec) { s.Routers[0].Service = "x" }, "unknown service"},
		{"unknown middleware", func(s *TraefikSpec) { s.Routers[0].Middlewares = []string{"x"} }, "unknown middleware"},
		{"unknown resolver", func(s *TraefikSpec) { s.Routers[0].TLS.CertResolver = "x" }, "unknown certificate resolver"},
		{"match all", func(s *TraefikSpec) { s.Routers[0].Match = Match{} }, "matches everything"},
		{"rule injection", func(s *TraefikSpec) { s.Routers[0].Match.Hosts = []string{"a`) || Host(`b"} }, "invalid"},
		{"wildcard host", func(s *TraefikSpec) { s.Routers[0].Match.Hosts = []string{"*.example.org"} }, "invalid"},
		{"server credentials", func(s *TraefikSpec) { s.Services[0].Servers = []string{"http://u:p@app:80"} }, "must be an http(s) URL"},
		{"server path", func(s *TraefikSpec) { s.Services[0].Servers = []string{"http://app/x"} }, "must be an http(s) URL"},
		{"bad email", func(s *TraefikSpec) { s.Resolvers[0].Email = "nope" }, "email"},
		{"staging and ca", func(s *TraefikSpec) { s.Resolvers[0].CAServer = "https://ca.example/dir" }, "exclude each other"},
		{"http ca", func(s *TraefikSpec) { s.Resolvers[0].Staging, s.Resolvers[0].CAServer = false, "http://ca.example" }, "https URL"},
		{"http challenge entry point", func(s *TraefikSpec) { s.Resolvers[0].Challenge.EntryPoint = "x" }, "existing entryPoint"},
		{"dns env _FILE", func(s *TraefikSpec) {
			s.Resolvers[0].Challenge = Challenge{Type: "dns", DNSProvider: "cloudflare", EnvFiles: map[string]string{"CF_API_TOKEN_FILE": "cf"}}
		}, "envFiles"},
		{"resolver without host pin", func(s *TraefikSpec) { s.Placement.HostID = "" }, "pinned to a host"},
		{"header credential", func(s *TraefikSpec) {
			s.Middlewares[0].Headers.Request = map[string]string{"Authorization": "Bearer x"}
		}, "credential"},
		{"mixed middleware", func(s *TraefikSpec) { s.Middlewares[1].IPAllowList = []string{"10.0.0.0/8"} }, "exactly its own settings"},
		{"bad cidr", func(s *TraefikSpec) {
			s.Middlewares = append(s.Middlewares, Middleware{Name: "ip", Type: MWIPAllowList, IPAllowList: []string{"10.0.0.1"}})
		}, "CIDR"},
		{"unknown middleware type", func(s *TraefikSpec) { s.Middlewares[0].Type = "plugin" }, "not supported"},
		{"redirect to self", func(s *TraefikSpec) { s.EntryPoints[0].RedirectTo = "web" }, "another entry point"},
		{"unpinned image", func(s *TraefikSpec) { s.Image = "traefik:latest" }, "latest"},
		{"duplicate router", func(s *TraefikSpec) { s.Routers = append(s.Routers, s.Routers[0]) }, "twice"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			s := goodTraefik()
			tc.mut(&s)
			err := Traefik{}.Validate(raw(t, s))
			if !errors.Is(err, ErrInvalidSpec) || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("got %v, want ErrInvalidSpec mentioning %q", err, tc.want)
			}
		})
	}
	if err := (Traefik{}).Validate(raw(t, goodTraefik())); err != nil {
		t.Fatalf("good spec: %v", err)
	}
}

const wantDynamic = `# Generated by the manager. Contains no secret values; secrets are referenced as files below /run/secrets.
http:
  routers:
    app:
      rule: "(Host(` + "`app.example.org`" + `)) && PathPrefix(` + "`/`" + `)"
      entryPoints:
        - "websecure"
      service: "app"
      middlewares:
        - "sec"
        - "admin"
      tls:
        certResolver: "le"
  services:
    app:
      loadBalancer:
        servers:
          - url: "http://app:8080"
        passHostHeader: true
        healthCheck:
          path: "/healthz"
          interval: "10s"
  middlewares:
    admin:
      basicAuth:
        usersFile: "/run/secrets/admin-users"
    sec:
      headers:
        customResponseHeaders:
          X-Frame-Options: "DENY"
        stsSeconds: 31536000
`

func TestRenderDynamicGolden(t *testing.T) {
	s := goodTraefik()
	s.Routers[0].Match.Hosts = []string{"app.example.org"}
	got := s.RenderDynamic()
	// A single host renders without parentheses; fix the expectation to the
	// documented format.
	want := strings.Replace(wantDynamic, "(Host(`app.example.org`))", "Host(`app.example.org`)", 1)
	if got != want {
		t.Fatalf("dynamic YAML differs.\n--- got\n%s\n--- want\n%s", got, want)
	}
}

func TestRenderStaticGolden(t *testing.T) {
	got := goodTraefik().RenderStatic()
	for _, w := range []string{
		"api:\n  dashboard: false\n",
		"certificatesResolvers:\n  le:\n    acme:\n",
		"      caServer: \"" + LetsEncryptStaging + "\"\n",
		"      email: \"ops@example.org\"\n",
		"      httpChallenge:\n        entryPoint: \"web\"\n",
		"      storage: \"/acme/le.json\"\n",
		"entryPoints:\n  web:\n    address: \":80\"\n    http:\n      redirections:\n        entryPoint:\n          permanent: true\n          scheme: \"https\"\n          to: \"websecure\"\n",
		"  websecure:\n    address: \":443\"\n",
		"providers:\n  file:\n    filename: \"/etc/traefik/dynamic.yml\"\n    watch: true\n",
	} {
		if !strings.Contains(got, w) {
			t.Errorf("static YAML lacks:\n%s\n--- got\n%s", w, got)
		}
	}
	if got != goodTraefik().RenderStatic() {
		t.Error("rendering is not deterministic")
	}
}

func TestRenderedOutputHasNoSecrets(t *testing.T) {
	s := goodTraefik()
	s.Resolvers[0].Challenge = Challenge{Type: "dns", DNSProvider: "cloudflare", EnvFiles: map[string]string{"CF_DNS_API_TOKEN": "cf-token-secret"}}
	s.Resolvers[0].Staging = false
	p, err := Traefik{}.Plan(PlanInput{Context: ctx(), Spec: raw(t, s)})
	if err != nil {
		t.Fatal(err)
	}
	var all strings.Builder
	for _, a := range p.Artifacts {
		all.WriteString(a.Content)
	}
	out := all.String()
	// Only the secret's name and its mount path may appear, never a value:
	// the model has no field for one. The provider variable is passed as
	// CF_DNS_API_TOKEN_FILE.
	if !strings.Contains(out, `"CF_DNS_API_TOKEN_FILE=/run/secrets/cf-token-secret"`) {
		t.Errorf("secret file variable missing:\n%s", out)
	}
	if strings.Contains(out, "CF_DNS_API_TOKEN=") {
		t.Error("a literal token variable is rendered")
	}
	// Strictness: no field of the model can hold a password or hash.
	if err := (Traefik{}).Validate(raw(t, map[string]any{"image": "traefik:v3", "entryPoints": []any{map[string]any{"name": "w", "port": 80}},
		"middlewares": []any{map[string]any{"name": "a", "type": "basicAuth", "basicAuth": map[string]any{"users": []string{"u:$apr1$x"}}}}})); !errors.Is(err, ErrInvalidSpec) {
		t.Errorf("inline users accepted: %v", err)
	}
}

func TestTraefikPlan(t *testing.T) {
	p, err := Traefik{}.Plan(PlanInput{Context: ctx(), Spec: raw(t, goodTraefik())})
	if err != nil {
		t.Fatal(err)
	}
	var kinds []StepKind
	for _, s := range p.Steps {
		kinds = append(kinds, s.Kind)
	}
	if !slices.Equal(kinds, []StepKind{StepCreateVolume, StepInitIdentity, StepCreateService, StepDeliverConfig}) {
		t.Fatalf("steps %v", kinds)
	}
	svc := p.Steps[2].Spec
	if svc.Replicas != 1 || svc.Labels[LabelServiceType] != TypeTraefik || !slices.Equal(svc.Secrets, []string{"admin-users"}) ||
		len(svc.Mounts) != 1 || svc.Mounts[0].Target != TraefikACMEDir {
		t.Fatalf("%+v", svc)
	}
	if !slices.Contains(svc.Args, "--entryPoints.websecure.address=:443") || !slices.Contains(svc.Args, "--api.dashboard=false") {
		t.Fatalf("args %v", svc.Args)
	}
	if len(svc.PublishedPorts()) != 2 {
		t.Fatalf("ports %+v", svc.Ports)
	}
	// Ports are published by the agent now; creating the dynamic config as a
	// Swarm config is not possible: the plan must say so and refuse to run.
	if p.Executable() || len(p.Blockers) != 1 {
		t.Fatalf("blockers %v", p.Blockers)
	}
	names := map[string]bool{}
	for _, a := range p.Artifacts {
		names[a.Name] = true
	}
	for _, n := range []string{"swarm-service.json", "traefik-static.yml", "traefik-dynamic.yml"} {
		if !names[n] {
			t.Errorf("artifact %s missing", n)
		}
	}
	w := strings.Join(p.Warnings, "\n")
	if !strings.Contains(w, "one replica") {
		t.Errorf("warnings lack the one-replica hint:\n%s", w)
	}
	if strings.Contains(w, "published on port 80") {
		t.Error("web is published on 80: no HTTP-challenge warning expected")
	}
	if strings.Contains(w, "production CA") {
		t.Error("staging resolver must not warn about the production CA")
	}
}

func TestTraefikDeleteAndHealth(t *testing.T) {
	d, err := Traefik{}.DeletePlan(PlanInput{Context: ctx(), Spec: raw(t, goodTraefik()), RemoveVolumes: true})
	if err != nil || len(d.Steps) != 2 || d.Type != TypeTraefik || d.Steps[1].Kind != StepRemoveVolume {
		t.Fatalf("%+v %v", d, err)
	}
	h, err := Traefik{}.Health(HealthInput{Spec: raw(t, goodTraefik()), Observed: Observation{}})
	if err != nil || h.State != HealthUnknown {
		t.Fatalf("%v %v", h, err)
	}
}
