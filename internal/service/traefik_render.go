// Rendering of the Traefik model. Both outputs are previews for the user and
// the generated configuration of the service. They contain names, paths and
// literal non-secret values only: secrets appear as the Swarm secret name
// behind /run/secrets, never as a value (the model has no field for one).

type kv struct{ path, val string }

// staticKV is the static configuration as flat Traefik option paths.
func (t TraefikSpec) staticKV() []kv {
	level := t.LogLevel
	if level == "" {
		level = "INFO"
	}
	out := []kv{
		{"api.dashboard", "false"}, // the dashboard and the insecure API stay off
		{"log.level", level},
	}
	if t.hasDynamic() {
		out = append(out, kv{"providers.file.filename", TraefikDynamicFile}, kv{"providers.file.watch", "true"})
	}
	for _, e := range t.EntryPoints {
		base := "entryPoints." + e.Name
		out = append(out, kv{base + ".address", fmt.Sprintf(":%d", e.Port)})
		if e.RedirectTo != "" {
			r := base + ".http.redirections.entryPoint"
			out = append(out, kv{r + ".to", e.RedirectTo}, kv{r + ".scheme", "https"}, kv{r + ".permanent", "true"})
		}
	}
	for _, r := range t.Resolvers {
		base := "certificatesResolvers." + r.Name + ".acme"
		out = append(out, kv{base + ".email", r.Email}, kv{base + ".storage", path.Join(TraefikACMEDir, r.Name+".json")})
		switch {
		case r.Staging:
			out = append(out, kv{base + ".caServer", LetsEncryptStaging})
		case r.CAServer != "":
			out = append(out, kv{base + ".caServer", r.CAServer})
		}
		switch r.Challenge.Type {
		case "http":
			out = append(out, kv{base + ".httpChallenge.entryPoint", r.Challenge.EntryPoint})
		case "tls":
			out = append(out, kv{base + ".tlsChallenge", "true"})
		case "dns":
			out = append(out, kv{base + ".dnsChallenge.provider", r.Challenge.DNSProvider})
		}
	}
	slices.SortStableFunc(out, func(a, b kv) int { return strings.Compare(a.path, b.path) })
	return out
}

// staticArgs are the static options as command-line flags. Traefik accepts
// the same option paths on the command line as in the static file.
func (t TraefikSpec) staticArgs() []string {
	var out []string
	for _, o := range t.staticKV() {
		out = append(out, "--"+o.path+"="+o.val)
	}
	return out
}

// RenderStatic renders the static configuration as YAML. It is what the
// command-line flags of the service amount to.
func (t TraefikSpec) RenderStatic() string {
	root := yMap()
	for _, o := range t.staticKV() {
		insertPath(root, strings.Split(o.path, "."), o.val)
	}
	return "# Generated by the manager. Equivalent to the command-line flags of the service.\n" + root.render()
}

func insertPath(n *ynode, parts []string, val string) {
	for i, p := range parts {
		last := i == len(parts)-1
		var child *ynode
		for _, e := range n.mapping {
			if e.key == p {
				child = e.val
				break
			}
		}
		if last {
			switch val {
			case "true", "false":
				n.set(p, yBool(val == "true"))
			default:
				n.set(p, yString(val))
			}
			return
		}
		if child == nil {
			child = yMap()
			n.set(p, child)
		}
		n = child
	}
}

func (m Match) rule() string {
	var parts []string
	switch len(m.Hosts) {
	case 0:
	case 1:
		parts = append(parts, "Host(`"+m.Hosts[0]+"`)")
	default:
		var hs []string
		for _, h := range m.Hosts {
			hs = append(hs, "Host(`"+h+"`)")
		}
		parts = append(parts, "("+strings.Join(hs, " || ")+")")
	}
	if m.Path != "" {
		parts = append(parts, "Path(`"+m.Path+"`)")
	}
	if m.PathPrefix != "" {
		parts = append(parts, "PathPrefix(`"+m.PathPrefix+"`)")
	}
	return strings.Join(parts, " && ")
}

func sortedBy[T any](in []T, name func(T) string) []T {
	out := slices.Clone(in)
	slices.SortFunc(out, func(a, b T) int { return strings.Compare(name(a), name(b)) })
	return out
}

func yStringMap(m map[string]string) *ynode {
	n := yMap()
	for _, k := range sortedKeys(m) {
		n.set(k, yString(m[k]))
	}
	return n
}

// RenderDynamic renders the dynamic configuration (the file provider's
// file): routers, services and middlewares of the http section.
func (t TraefikSpec) RenderDynamic() string {
	http := yMap()
	if len(t.Routers) > 0 {
		rs := yMap()
		for _, r := range sortedBy(t.Routers, func(r Router) string { return r.Name }) {
			n := yMap().set("rule", yString(r.Match.rule())).set("entryPoints", yStrings(sortedUnique(r.EntryPoints))).set("service", yString(r.Service))
			if len(r.Middlewares) > 0 {
				n.set("middlewares", yStrings(r.Middlewares)) // order matters
			}
			if r.Priority > 0 {
				n.set("priority", yInt(r.Priority))
			}
			if r.TLS != nil {
				tls := yMap()
				if r.TLS.CertResolver != "" {
					tls.set("certResolver", yString(r.TLS.CertResolver))
				}
				n.set("tls", tls)
			}
			rs.set(r.Name, n)
		}
		http.set("routers", rs)
	}
	if len(t.Services) > 0 {
		ss := yMap()
		for _, b := range sortedBy(t.Services, func(b Backend) string { return b.Name }) {
			servers := &ynode{seq: []*ynode{}}
			for _, s := range b.Servers {
				servers.seq = append(servers.seq, yMap().set("url", yString(s)))
			}
			lb := yMap().set("servers", servers)
			if b.PassHostHeader != nil {
				lb.set("passHostHeader", yBool(*b.PassHostHeader))
			}
			if b.HealthPath != "" {
				hc := yMap().set("path", yString(b.HealthPath))
				if b.HealthIntervalSeconds > 0 {
					hc.set("interval", yString(fmt.Sprintf("%ds", b.HealthIntervalSeconds)))
				}
				lb.set("healthCheck", hc)
			}
			ss.set(b.Name, yMap().set("loadBalancer", lb))
		}
		http.set("services", ss)
	}
	if len(t.Middlewares) > 0 {
		ms := yMap()
		for _, m := range sortedBy(t.Middlewares, func(m Middleware) string { return m.Name }) {
			ms.set(m.Name, m.node())
		}
		http.set("middlewares", ms)
	}
	root := yMap().set("http", http)
	return "# Generated by the manager. Contains no secret values; secrets are referenced as files below " + SecretsDir + ".\n" + root.render()
}

func (m Middleware) node() *ynode {
	switch m.Type {
	case MWRedirectScheme:
		n := yMap().set("scheme", yString(m.RedirectScheme.Scheme))
		if m.RedirectScheme.Permanent {
			n.set("permanent", yBool(true))
		}
		return yMap().set("redirectScheme", n)
	case MWStripPrefix:
		return yMap().set("stripPrefix", yMap().set("prefixes", yStrings(m.StripPrefix)))
	case MWHeaders:
		n := yMap()
		if len(m.Headers.Request) > 0 {
			n.set("customRequestHeaders", yStringMap(m.Headers.Request))
		}
		if len(m.Headers.Response) > 0 {
			n.set("customResponseHeaders", yStringMap(m.Headers.Response))
		}
		if m.Headers.STSSeconds > 0 {
			n.set("stsSeconds", yInt(m.Headers.STSSeconds))
		}
		return yMap().set("headers", n)
	case MWRateLimit:
		n := yMap().set("average", yInt(m.RateLimit.Average))
		if m.RateLimit.Burst > 0 {
			n.set("burst", yInt(m.RateLimit.Burst))
		}
		return yMap().set("rateLimit", n)
	case MWBasicAuth:
		return yMap().set("basicAuth", yMap().set("usersFile", yString(path.Join(SecretsDir, m.BasicAuthUsersSecret))))
	case MWIPAllowList:
		return yMap().set("ipAllowList", yMap().set("sourceRange", yStrings(m.IPAllowList)))
	}
	return yMap().set("compress", yMap())
}
