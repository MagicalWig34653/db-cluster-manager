package service

import (
	"encoding/json"
	"fmt"
	"net"
	"path"
	"slices"
	"strings"
)

// NFSExportRoot is where the data volume of an NFS service is mounted.
const NFSExportRoot = "/export"

// nfsPort is the single port of NFSv4.
const nfsPort = 2049

// NFS squash modes.
const (
	NFSRootSquash   = "root_squash"
	NFSAllSquash    = "all_squash"
	NFSNoRootSquash = "no_root_squash"
)

// NFSExport is one exported directory.
type NFSExport struct {
	// Path is a directory below the export root, for example "/shared".
	// "/" exports the whole volume.
	Path string `json:"path"`
	// Clients are CIDR ranges or single IPs allowed to mount. A wildcard
	// is not accepted.
	Clients  []string `json:"clients"`
	ReadOnly bool     `json:"readOnly,omitempty"`
	// Squash is "root_squash" (default), "all_squash" or "no_root_squash".
	Squash string `json:"squash,omitempty"`
}

// NFSSpec is the desired state of an NFSv4 server in a container.
//
// Feasibility: a kernel NFS server in a container needs the nfsd kernel
// module on the host, CAP_SYS_ADMIN (in practice privileged mode), and it
// competes with the host's own NFS server for port 2049. Swarm services
// cannot be privileged and the agent's service spec has no capability
// field. The plan therefore always carries a blocker: the type is a preview
// until the feasibility experiment of release R8 has run on the lab (or the
// type is deferred). A user-space NFS server image would need no
// privileges but is not evaluated.
type NFSSpec struct {
	StorageBase
	Exports []NFSExport `json:"exports"`
	// PublishedPort is the host port of NFSv4 (default 2049). NFS is
	// published in host mode: the clients mount from the pinned host.
	PublishedPort int `json:"publishedPort,omitempty"`
}

// NFS is the NFS service type.
type NFS struct{}

var _ Type = NFS{}

// Name implements Type.
func (NFS) Name() string { return TypeNFS }

func decodeNFS(raw json.RawMessage) (NFSSpec, error) {
	var n NFSSpec
	if err := decodeStrict(raw, &n); err != nil {
		return NFSSpec{}, err
	}
	return n, n.validate()
}

// Validate implements Type.
func (NFS) Validate(spec json.RawMessage) error {
	_, err := decodeNFS(spec)
	return err
}

func (n NFSSpec) publishedPort() int {
	if n.PublishedPort == 0 {
		return nfsPort
	}
	return n.PublishedPort
}

func validNFSClient(c string) bool {
	if net.ParseIP(c) != nil {
		return true
	}
	_, _, err := net.ParseCIDR(c)
	return err == nil
}

func (n NFSSpec) validate() error {
	var p problems
	n.StorageBase.validate(&p)
	if pp := n.publishedPort(); pp < 1 || pp > 65535 {
		p.addf("publishedPort %d out of range", pp)
	}
	if len(n.Exports) == 0 {
		p.addf("at least one export is required")
	}
	seen := map[string]bool{}
	for _, e := range n.Exports {
		switch {
		case !path.IsAbs(e.Path) || path.Clean(e.Path) != e.Path || strings.ContainsAny(e.Path, " \t\r\n\x00(),\\\"'"):
			p.addf("export path %q must be a clean absolute path without spaces or exports syntax", e.Path)
		case seen[e.Path]:
			p.addf("export %q listed twice", e.Path)
		}
		seen[e.Path] = true
		if len(e.Clients) == 0 {
			p.addf("export %q needs at least one client address or range", e.Path)
		}
		for _, c := range e.Clients {
			if !validNFSClient(c) {
				p.addf("export %q: client %q is not an IP address or CIDR range (no wildcards or host names)", e.Path, c)
			}
			if c == "0.0.0.0/0" || c == "::/0" {
				p.addf("export %q: client %q exports to every address", e.Path, c)
			}
		}
		switch e.Squash {
		case "", NFSRootSquash, NFSAllSquash, NFSNoRootSquash:
		default:
			p.addf("export %q: squash %q (want root_squash, all_squash or no_root_squash)", e.Path, e.Squash)
		}
	}
	return p.err()
}

// RenderExports renders the exports file of the server. Every export is
// NFSv4 with sync writes and no subtree checking.
func (n NFSSpec) RenderExports() string {
	var b strings.Builder
	b.WriteString("# Generated by the manager. Mounted below " + NFSExportRoot + ".\n")
	es := slices.Clone(n.Exports)
	slices.SortFunc(es, func(a, b NFSExport) int { return strings.Compare(a.Path, b.Path) })
	for _, e := range es {
		squash := e.Squash
		if squash == "" {
			squash = NFSRootSquash
		}
		rw := "rw"
		if e.ReadOnly {
			rw = "ro"
		}
		cs := slices.Clone(e.Clients)
		slices.Sort(cs)
		var parts []string
		for _, c := range cs {
			parts = append(parts, fmt.Sprintf("%s(%s,sync,no_subtree_check,%s)", c, rw, squash))
		}
		root := NFSExportRoot
		if e.Path != "/" {
			root = path.Join(NFSExportRoot, e.Path)
		}
		fmt.Fprintf(&b, "%s %s\n", root, strings.Join(parts, " "))
	}
	return b.String()
}

func (n NFSSpec) container() ContainerSpec {
	c := n.StorageBase.container(NFSExportRoot)
	c.Env = []EnvVar{{Name: "DBCM_NFS_EXPORT_ROOT", Value: NFSExportRoot}, {Name: "DBCM_NFS_VERSION", Value: "4"}}
	return c
}

// Plan implements Type.
func (NFS) Plan(in PlanInput) (Plan, error) {
	if err := in.check(); err != nil {
		return Plan{}, err
	}
	n, err := decodeNFS(in.Spec)
	if err != nil {
		return Plan{}, err
	}
	p, err := storagePlan(in, TypeNFS, n.container(), func(sp *ServiceSpec) {
		sp.Ports = []Port{{Target: nfsPort, Published: n.publishedPort(), Protocol: "tcp", Mode: "host"}}
	})
	if err != nil {
		return Plan{}, err
	}
	ports, err := portArtifact(*p.Steps[len(p.Steps)-1].Spec)
	if err != nil {
		return Plan{}, err
	}
	p.Artifacts = append(p.Artifacts,
		Artifact{Name: "nfs-exports", MediaType: "text/plain", Content: n.RenderExports()}, ports)
	p.Blockers = append(p.Blockers,
		"an NFS server container needs CAP_SYS_ADMIN (privileged mode) and the nfsd kernel module on the host: the agent's service spec has no capability or privileged field and Swarm services cannot run privileged",
		"the exports file is not delivered: the agent cannot create a Swarm config yet and the image contract for it is not decided")
	p.Warnings = append(p.Warnings, storageBackupWarning,
		"NFSv4 has no encryption of its own: traffic and file data cross the network unencrypted unless the network is trusted or wrapped (Kerberos, WireGuard)",
		"the host must not run its own NFS server on port "+fmt.Sprint(n.publishedPort())+"; the kernel NFS server is a host-wide singleton, so two NFS services on one host cannot coexist",
		"clients are restricted by IP address only; NFS trusts the numeric user and group IDs the client sends")
	for _, e := range n.Exports {
		if e.Squash == NFSNoRootSquash {
			p.Warnings = append(p.Warnings, fmt.Sprintf("export %s uses no_root_squash: root on a client is root on the exported files", e.Path))
		}
	}
	return p, nil
}

// DeletePlan implements Type.
func (NFS) DeletePlan(in PlanInput) (Plan, error) {
	if err := in.check(); err != nil {
		return Plan{}, err
	}
	n, err := decodeNFS(in.Spec)
	if err != nil {
		return Plan{}, err
	}
	return n.container().deletePlan(in, TypeNFS), nil
}

// Health implements Type.
func (NFS) Health(in HealthInput) (Health, error) {
	if _, err := decodeNFS(in.Spec); err != nil {
		return Health{}, err
	}
	return observationHealth(in.Observed), nil
}
