const appDir = "/app"

// ---------------------------------------------------------------- application runtimes

func (b *build) appBase(port int64) {
	b.readonly = append(b.readonly, appDir)
	b.workdir = appDir
	b.expose = int(port)
}

func (b *build) node() {
	o := b.sel["node"].Settings
	b.appBase(gi(o, "port"))
	b.env["NODE_ENV"] = gs(o, "nodeEnv")
	cmd := []string{b.sup["node"].Binary}
	if m := gi(o, "maxOldSpaceMb"); m > 0 {
		cmd = append(cmd, "--max-old-space-size="+strconv.FormatInt(m, 10))
	}
	cmd = append(cmd, gs(o, "entryPoint"))
	b.runtime = append(b.runtime, "CMD "+arr(cmd...))
}

func (b *build) python() {
	o := b.sel["python"].Settings
	b.appBase(gi(o, "port"))
	b.env["PYTHONDONTWRITEBYTECODE"] = "1"
	b.env["PYTHONUNBUFFERED"] = "1"
	cmd := []string{b.sup["python"].Binary, "-m", "gunicorn", "--chdir", appDir,
		"--bind", fmt.Sprintf("0.0.0.0:%d", gi(o, "port")),
		"--workers", strconv.FormatInt(gi(o, "workers"), 10),
		"--threads", strconv.FormatInt(gi(o, "threads"), 10),
		"--timeout", strconv.FormatInt(gi(o, "timeout"), 10),
		"--worker-tmp-dir", "/tmp",
		"--forwarded-allow-ips", gs(o, "forwardedAllowIps"),
		"--error-logfile", "-"}
	if gb(o, "accessLog") {
		cmd = append(cmd, "--access-logfile", "-")
	}
	cmd = append(cmd, gs(o, "app"))
	b.runtime = append(b.runtime, "CMD "+arr(cmd...))
}

func (b *build) java() {
	o := b.sel["java"].Settings
	b.appBase(gi(o, "port"))
	cmd := []string{b.sup["java"].Binary}
	switch gs(o, "garbageCollector") {
	case "g1":
		cmd = append(cmd, "-XX:+UseG1GC")
	case "serial":
		cmd = append(cmd, "-XX:+UseSerialGC")
	case "parallel":
		cmd = append(cmd, "-XX:+UseParallelGC")
	}
	cmd = append(cmd, fmt.Sprintf("-XX:MaxRAMPercentage=%d", gi(o, "maxRamPercentage")))
	if gb(o, "exitOnOutOfMemory") {
		cmd = append(cmd, "-XX:+ExitOnOutOfMemoryError")
	}
	cmd = append(cmd, "-Djava.io.tmpdir=/tmp", "-jar", gs(o, "jarPath"))
	b.runtime = append(b.runtime, "CMD "+arr(cmd...))
}

// ---------------------------------------------------------------- SFTP

func (b *build) sftp() {
	o := b.sel["sftp"].Settings
	su := b.sup["sftp"]
	var c strings.Builder
	c.WriteString("# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\n")
	fmt.Fprintf(&c, "Port %d\nListenAddress 0.0.0.0\nHostKey %s\nPidFile /tmp/sshd.pid\nAuthorizedKeysFile %s\n", gi(o, "port"), gs(o, "hostKeyPath"), gs(o, "authorizedKeysPath"))
	c.WriteString("AllowUsers app\nPermitRootLogin no\nPubkeyAuthentication yes\nPasswordAuthentication no\nKbdInteractiveAuthentication no\nUsePAM no\nStrictModes no\n")
	fmt.Fprintf(&c, "MaxAuthTries %d\nLoginGraceTime 30\n", gi(o, "maxAuthTries"))
	c.WriteString("X11Forwarding no\nAllowTcpForwarding no\nAllowAgentForwarding no\nPermitTTY no\nPermitTunnel no\nGatewayPorts no\nPrintMotd no\nLogLevel INFO\n")
	force := fmt.Sprintf("internal-sftp -d %s -u %s", gs(o, "dataDir"), gs(o, "umask"))
	if gb(o, "readOnly") {
		force += " -R"
	}
	fmt.Fprintf(&c, "Subsystem sftp internal-sftp\nForceCommand %s\n", force)
	b.files = append(b.files, imagebuild.File{Path: "sshd/sshd_config", Mode: 0o644, Content: c.String()})
	b.readonly = append(b.readonly, confRoot+"/sshd")
	b.writable = append(b.writable, gs(o, "dataDir"), "/run/sshd")
	b.copies = append(b.copies, fmt.Sprintf("COPY sshd/sshd_config %s/sshd/sshd_config", confRoot))
	// A throw-away key lets sshd -t test the configuration; it is removed in
	// the same RUN and never reaches a layer. The real host key is a secret
	// mounted at run time.
	b.checks = append(b.checks, fmt.Sprintf("RUN ssh-keygen -q -t ed25519 -N \"\" -f /tmp/dbcm-check-key && %s -t -h /tmp/dbcm-check-key -f %s/sshd/sshd_config && rm -f /tmp/dbcm-check-key /tmp/dbcm-check-key.pub", su.Binary, confRoot))
	b.expose = int(gi(o, "port"))
	b.runtime = append(b.runtime, "CMD "+arr(su.Binary, "-D", "-e", "-f", confRoot+"/sshd/sshd_config"))
}

// ---------------------------------------------------------------- job runner

func (b *build) jobs() {
	o := b.sel["jobrunner"].Settings
	var s strings.Builder
	s.WriteString("#!/bin/sh\n# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\n# One preset job at a fixed interval; credentials come from the service environment or secrets.\nset -u\n")
	fmt.Fprintf(&s, "INTERVAL=%d\ntrap 'exit 0' TERM INT\nrun_job() {\n", gi(o, "intervalSeconds"))
	switch gs(o, "job") {
	case "restic-backup":
		fmt.Fprintf(&s, "    restic backup --host dbcm '%s'", gs(o, "sourceDir"))
		if k := gi(o, "resticKeepDaily"); k > 0 {
			fmt.Fprintf(&s, " &&\n    restic forget --keep-daily %d --prune", k)
		}
		s.WriteString("\n")
		b.env["RESTIC_CACHE_DIR"] = "/tmp/restic-cache"
	case "rclone-sync":
		fmt.Fprintf(&s, "    rclone sync '%s' '%s'\n", gs(o, "sourceDir"), gs(o, "rcloneDestination"))
	}
	s.WriteString("}\nwait_interval() {\n    sleep \"$INTERVAL\" &\n    wait $!\n}\n")
	if !gb(o, "runOnStart") {
		s.WriteString("wait_interval\n")
	}
	onFail := ":"
	if gs(o, "onFailure") == "exit" {
		onFail = "exit \"$rc\""
	}
	fmt.Fprintf(&s, "while true; do\n    echo \"dbcm-jobs: running %s\"\n    if run_job; then\n        echo \"dbcm-jobs: done\"\n    else\n        rc=$?\n        echo \"dbcm-jobs: failed with status $rc\" >&2\n        %s\n    fi\n    wait_interval\ndone\n", gs(o, "job"), onFail)
	b.files = append(b.files, imagebuild.File{Path: "jobs/run.sh", Mode: 0o755, Content: s.String()})
	b.copies = append(b.copies, "COPY jobs/run.sh /usr/local/bin/dbcm-jobs")
	b.runtime = append(b.runtime, "CMD "+arr("/usr/local/bin/dbcm-jobs"))
}

// ---------------------------------------------------------------- system settings

// systemPackages maps the generator-added packages to the family's names.
var systemPackages = map[string]map[string]string{
	"tzdata":          {"alpine": "tzdata", "debian": "tzdata", "rhel": "tzdata"},
	"curl":            {"alpine": "curl", "debian": "curl", "rhel": "curl"},
	"ca-certificates": {"alpine": "ca-certificates", "debian": "ca-certificates", "rhel": "ca-certificates"},
	"locales":         {"debian": "locales"},
	"langpack-en":     {"rhel": "glibc-langpack-en"},
	"langpack-de":     {"rhel": "glibc-langpack-de"},
}

func (b *build) sysPkg(key string) {
	if name := systemPackages[key][b.family]; name != "" {
		add(b.packages, b.family, "system", name, "")
	}
}

func (b *build) system() {
	o := b.sel["system"].Settings
	b.sysPkg("tzdata")
	b.env["TZ"] = gs(o, "timezone")
	loc := gs(o, "locale")
	b.env["LANG"] = loc
	if loc != "C.UTF-8" {
		switch b.family {
		case "debian":
			b.sysPkg("locales")
			b.preUser = append(b.preUser, fmt.Sprintf("RUN sed -i 's/^# *\\(%s UTF-8\\)/\\1/' /etc/locale.gen && locale-gen", strings.TrimSuffix(loc, ".UTF-8")+".UTF-8"))
		case "rhel":
			if strings.HasPrefix(loc, "de_") {
				b.sysPkg("langpack-de")
			} else {
				b.sysPkg("langpack-en")
			}
		}
	}
	if pemText := gs(o, "extraCaPem"); pemText != "" {
		b.sysPkg("ca-certificates")
		rest := []byte(pemText)
		i := 0
		for {
			var blk *pem.Block
			blk, rest = pem.Decode(rest)
			if blk == nil {
				break
			}
			i++
			path := fmt.Sprintf("certs/extra-ca-%d.crt", i)
			b.files = append(b.files, imagebuild.File{Path: path, Mode: 0o644, Content: string(pem.EncodeToMemory(blk))})
			dst := fmt.Sprintf("/usr/local/share/ca-certificates/dbcm-extra-ca-%d.crt", i)
			if b.family == "rhel" {
				dst = fmt.Sprintf("/etc/pki/ca-trust/source/anchors/dbcm-extra-ca-%d.crt", i)
			}
			b.preUser = append(b.preUser, fmt.Sprintf("COPY %s %s", path, dst))
		}
		if b.family == "rhel" {
			b.preUser = append(b.preUser, "RUN update-ca-trust extract")
		} else {
			b.preUser = append(b.preUser, "RUN update-ca-certificates")
		}
	}
	if hc := gs(o, "healthcheck"); hc != "none" && hc != "" {
		b.sysPkg("curl")
		path := gs(o, "healthcheckPath")
		port := 0
		for _, id := range append(append([]string{}, webServerIDs...), appIDs...) {
			if s, ok := b.sel[id]; ok {
				port = webPort
				if p := gi(s.Settings, "port"); p > 0 {
					port = int(p)
				}
			}
		}
		if hc == "fpm-ping" {
			path = pingPath
		}
		b.health = fmt.Sprintf("HEALTHCHECK --interval=%ds --timeout=%ds --start-period=%ds --retries=%d CMD %s",
			gi(o, "healthcheckInterval"), gi(o, "healthcheckTimeout"), gi(o, "healthcheckStartPeriod"), gi(o, "healthcheckRetries"),
			arr("curl", "-fsS", "-o", "/dev/null", fmt.Sprintf("http://127.0.0.1:%d%s", port, path)))
	}
}
