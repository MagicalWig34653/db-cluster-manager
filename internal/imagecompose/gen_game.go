package imagecompose

import (
	"fmt"
	"strings"

	"github.com/MagicalWig34653/db-cluster-manager/internal/imagebuild"
)

const (
	minecraftPort = 25565
	minecraftData = "/data"
	minecraftJar  = "/opt/minecraft/server.jar"
	// Crossplay plugins live in the image and are copied to /data/plugins on
	// every start, because the /data volume hides anything baked in there.
	minecraftPlugins = "/opt/minecraft/plugins"
	bedrockPort      = 19132 // UDP, Geyser
)

// minecraftManaged are the server.properties keys the recipe controls. The
// entrypoint rewrites exactly these on every start and leaves the user's
// other keys in /data/server.properties untouched.
var minecraftManaged = []string{"server-port", "motd", "max-players", "difficulty", "view-distance", "online-mode"}

// minecraft renders the Minecraft Java Edition server: the jar is downloaded
// at build time from the official host pinned in the catalog and verified by
// hash; the JRE comes from the distribution (the package differs per
// Minecraft version, see the catalog matrix).
func (c *Catalog) minecraft(b *build) {
	sel := b.sel["minecraft"]
	o := sel.Settings
	comp, _ := c.Component("minecraft")
	cv, _ := comp.Version(sel.Version)
	art := cv.Artifacts[gs(o, "variant")] // presence is checked by Resolve
	// The directory is created first: ADD applies --chmod to a directory it
	// creates itself, which would make it unreadable (found in the lab build).
	crossplay := gb(o, "crossplay")
	dirs := "/opt/minecraft"
	if crossplay {
		dirs += " " + minecraftPlugins
	}
	b.preUser = append(b.preUser, "RUN mkdir -p -m 0755 "+dirs)
	b.preUser = append(b.preUser, fmt.Sprintf("ADD --checksum=sha256:%s --chmod=0644 %s %s", art.SHA256, art.URL, minecraftJar))
	if art.SHA1 != "" {
		// Mojang publishes SHA-1 only; it is checked in addition to the pinned SHA-256.
		b.preUser = append(b.preUser, fmt.Sprintf("RUN echo %q > /tmp/server.jar.sha1 && sha1sum -c /tmp/server.jar.sha1 && rm -f /tmp/server.jar.sha1", art.SHA1+"  "+minecraftJar))
	}

	if crossplay {
		for _, p := range []struct{ key, file string }{{"geyser", "Geyser-Spigot.jar"}, {"floodgate", "floodgate-spigot.jar"}} {
			pa := cv.Crossplay[p.key] // presence is checked by Resolve
			b.preUser = append(b.preUser, fmt.Sprintf("ADD --checksum=sha256:%s --chmod=0644 %s %s/%s", pa.SHA256, pa.URL, minecraftPlugins, p.file))
		}
	}

	managed := fmt.Sprintf("# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\nserver-port=%d\nmotd=%s\nmax-players=%d\ndifficulty=%s\nview-distance=%d\nonline-mode=%t\n",
		minecraftPort, gs(o, "motd"), gi(o, "maxPlayers"), gs(o, "difficulty"), gi(o, "viewDistance"), gb(o, "onlineMode"))
	// The file is only generated because Resolve refused a recipe without the
	// explicit acceptance; there is no default and no way around the field.
	eula := "# Written because the recipe states that the Minecraft EULA (https://www.minecraft.net/eula) was accepted.\neula=true\n"
	java := b.sup["minecraft"].Binary
	plugins := ""
	if crossplay {
		plugins = "mkdir -p plugins\ncp -f " + minecraftPlugins + "/*.jar plugins/\n"
	}
	entry := "#!/bin/sh\n# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\n" +
		"# Applies the managed server.properties keys on every start, keeps the others, then replaces the shell with the JVM.\nset -eu\n" +
		"cd " + minecraftData + "\ncfg=" + confRoot + "/minecraft\ntmp=" + minecraftData + "/.server.properties.dbcm\n" +
		"if [ -f server.properties ]; then\n  grep -v -E '^(" + strings.Join(minecraftManaged, "|") + ")=' server.properties > \"$tmp\" || true\nelse\n  : > \"$tmp\"\nfi\n" +
		"cat \"$cfg/managed.properties\" >> \"$tmp\"\nmv \"$tmp\" server.properties\ncp \"$cfg/eula.txt\" eula.txt\n" + plugins +
		fmt.Sprintf("exec %s -Xms%s -Xmx%s -XX:+ExitOnOutOfMemoryError -Djava.io.tmpdir=/tmp -jar %s nogui\n", java, gs(o, "memoryInitial"), gs(o, "memoryMax"), minecraftJar)
	b.files = append(b.files,
		imagebuild.File{Path: "minecraft/managed.properties", Mode: 0o644, Content: managed},
		imagebuild.File{Path: "minecraft/eula.txt", Mode: 0o644, Content: eula},
		imagebuild.File{Path: "minecraft/entrypoint.sh", Mode: 0o755, Content: entry},
	)
	b.readonly = append(b.readonly, confRoot+"/minecraft")
	b.writable = append(b.writable, minecraftData)
	b.copies = append(b.copies,
		fmt.Sprintf("COPY minecraft/managed.properties minecraft/eula.txt %s/minecraft/", confRoot),
		"COPY --chmod=0755 minecraft/entrypoint.sh /usr/local/bin/dbcm-minecraft",
		fmt.Sprintf("VOLUME [%q]", minecraftData))
	b.workdir = minecraftData
	b.expose = minecraftPort
	if crossplay {
		b.exposeUDP = bedrockPort
	}
	b.runtime = append(b.runtime, "ENTRYPOINT "+arr("/usr/local/bin/dbcm-minecraft"))
}
