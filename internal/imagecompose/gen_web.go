// headerSet returns the response headers of a security header preset. The
// values are fixed text; only the preset name comes from the recipe.
func headerSet(preset string) [][2]string {
	basic := [][2]string{
		{"X-Content-Type-Options", "nosniff"},
		{"X-Frame-Options", "SAMEORIGIN"},
		{"Referrer-Policy", "strict-origin-when-cross-origin"},
	}
	switch preset {
	case "strict":
		return append(basic,
			[2]string{"Strict-Transport-Security", "max-age=31536000"},
			[2]string{"Permissions-Policy", "camera=(), microphone=(), geolocation=()"},
			[2]string{"Cross-Origin-Opener-Policy", "same-origin"})
	case "api":
		return [][2]string{
			{"X-Content-Type-Options", "nosniff"},
			{"Cache-Control", "no-store"},
			{"Referrer-Policy", "no-referrer"},
			{"Content-Security-Policy", "default-src 'none'; frame-ancestors 'none'"},
		}
	}
	return basic
}

func headersOn(o map[string]any) [][2]string {
	if !gb(o, "securityHeaders") {
		return nil
	}
	return headerSet(gs(o, "securityHeadersPreset"))
}

func cidrList(s string) []string { return strings.Split(s, ",") }

// compressTypes are the MIME types worth compressing.
const compressTypes = "text/plain text/css application/json application/javascript text/xml application/xml image/svg+xml"

func (b *build) siteDirs(docroot string) {
	b.writable = append(b.writable, docroot)
}

// ---------------------------------------------------------------- nginx

func (b *build) nginx() {
	o := b.sel["nginx"].Settings
	_, php := b.sel["php"]
	b.siteDirs(gs(o, "documentRoot"))
	b.writable = append(b.writable, "/var/log/nginx")
	b.readonly = append(b.readonly, confRoot+"/nginx")
	ping := gs(b.sel["system"].Settings, "healthcheck") == "fpm-ping"
	b.files = append(b.files,
		imagebuild.File{Path: "nginx/nginx.conf", Mode: 0o644, Content: renderNginxConf(o)},
		imagebuild.File{Path: "nginx/default.conf", Mode: 0o644, Content: renderServerConf(o, php, ping)},
	)
	b.copies = append(b.copies,
		fmt.Sprintf("COPY nginx/nginx.conf %s/nginx/nginx.conf", confRoot),
		fmt.Sprintf("COPY nginx/default.conf %s/nginx/default.conf", confRoot))
	b.checks = append(b.checks, fmt.Sprintf("RUN nginx -t -c %s/nginx/nginx.conf", confRoot))
	b.expose = webPort
	b.runtime = append(b.runtime, "STOPSIGNAL SIGQUIT")
	if !php {
		b.runtime = append(b.runtime, "CMD "+arr(b.webCmdArray()...))
	}
}

func renderNginxConf(o map[string]any) string {
	var b strings.Builder
	b.WriteString("# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\n")
	brotli := gb(o, "brotli")
	if brotli {
		b.WriteString("load_module /usr/lib/nginx/modules/ngx_http_brotli_filter_module.so;\n")
	}
	fmt.Fprintf(&b, "worker_processes %v;\npid /tmp/nginx.pid;\nerror_log /dev/stderr warn;\n", o["workerProcesses"])
	fmt.Fprintf(&b, "events {\n    worker_connections %v;\n}\nhttp {\n", o["workerConnections"])
	b.WriteString("    include /etc/nginx/mime.types;\n    default_type application/octet-stream;\n")
	if gb(o, "accessLog") {
		b.WriteString("    access_log /dev/stdout;\n")
	} else {
		b.WriteString("    access_log off;\n")
	}
	b.WriteString("    sendfile on;\n")
	fmt.Fprintf(&b, "    server_tokens %s;\n    keepalive_timeout %v;\n    client_max_body_size %v;\n", b2(o["serverTokens"]), o["keepaliveTimeout"], o["clientMaxBodySize"])
	b.WriteString("    client_body_temp_path /tmp/nginx-client-body;\n    proxy_temp_path /tmp/nginx-proxy;\n    fastcgi_temp_path /tmp/nginx-fastcgi;\n    uwsgi_temp_path /tmp/nginx-uwsgi;\n    scgi_temp_path /tmp/nginx-scgi;\n")
	fmt.Fprintf(&b, "    gzip %s;\n", b2(o["gzip"]))
	if gb(o, "gzip") {
		fmt.Fprintf(&b, "    gzip_types %s;\n", compressTypes)
	}
	if brotli {
		fmt.Fprintf(&b, "    brotli on;\n    brotli_types %s;\n", compressTypes)
	}
	if mode := gs(o, "realIpMode"); mode != "off" && mode != "" {
		for _, cidr := range cidrList(gs(o, "trustedProxies")) {
			fmt.Fprintf(&b, "    set_real_ip_from %s;\n", cidr)
		}
		if mode == "x-forwarded-for" {
			b.WriteString("    real_ip_header X-Forwarded-For;\n    real_ip_recursive on;\n")
		} else {
			b.WriteString("    real_ip_header X-Real-IP;\n")
		}
	}
	if gb(o, "trustForwardedProto") {
		b.WriteString("    map $http_x_forwarded_proto $dbcm_https {\n        default \"\";\n        https on;\n    }\n")
	}
	if rl := gi(o, "rateLimit"); rl > 0 {
		fmt.Fprintf(&b, "    limit_req_zone $binary_remote_addr zone=dbcm_perip:10m rate=%dr/s;\n    limit_req_status 429;\n", rl)
	}
	fmt.Fprintf(&b, "    include %s/nginx/default.conf;\n}\n", confRoot)
	return b.String()
}

func renderServerConf(o map[string]any, php, ping bool) string {
	var b strings.Builder
	b.WriteString("# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\nserver {\n")
	fmt.Fprintf(&b, "    listen %d default_server;\n    server_name %v;\n    root %v;\n", webPort, o["serverName"], o["documentRoot"])
	if php {
		b.WriteString("    index index.php index.html;\n")
	} else {
		b.WriteString("    index index.html;\n")
	}
	for _, h := range headersOn(o) {
		fmt.Fprintf(&b, "    add_header %s \"%s\" always;\n", h[0], h[1])
	}
	if rl := gi(o, "rateLimit"); rl > 0 {
		fmt.Fprintf(&b, "    limit_req zone=dbcm_perip burst=%d nodelay;\n", gi(o, "rateLimitBurst"))
	}
	if php {
		if ping {
			fmt.Fprintf(&b, "    location = %s {\n        access_log off;\n        allow 127.0.0.1;\n        deny all;\n        limit_req off;\n        include /etc/nginx/fastcgi_params;\n        fastcgi_param SCRIPT_FILENAME %s;\n        fastcgi_param SCRIPT_NAME %s;\n        fastcgi_pass 127.0.0.1:%d;\n    }\n", pingPath, pingPath, pingPath, fpmPort)
		}
		b.WriteString("    location / {\n        try_files $uri $uri/ /index.php?$query_string;\n    }\n")
		fmt.Fprintf(&b, "    location ~ \\.php$ {\n        try_files $uri =404;\n        include /etc/nginx/fastcgi_params;\n        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;\n")
		if gb(o, "trustForwardedProto") {
			b.WriteString("        fastcgi_param HTTPS $dbcm_https if_not_empty;\n")
		}
		fmt.Fprintf(&b, "        fastcgi_pass 127.0.0.1:%d;\n        fastcgi_read_timeout %vs;\n    }\n", fpmPort, o["fastcgiReadTimeout"])
	} else {
		b.WriteString("    location / {\n        try_files $uri $uri/ =404;\n    }\n")
	}
	b.WriteString("    location ~ /\\.(?!well-known) {\n        deny all;\n    }\n}\n")
	return b.String()
}

// ---------------------------------------------------------------- apache

func (b *build) apache() {
	o := b.sel["apache"].Settings
	su := b.sup["apache"]
	_, php := b.sel["php"]
	b.siteDirs(gs(o, "documentRoot"))
	b.readonly = append(b.readonly, confRoot+"/apache")
	b.files = append(b.files, imagebuild.File{Path: "apache/httpd.conf", Mode: 0o644, Content: renderApacheConf(o, su, php)})
	b.copies = append(b.copies, fmt.Sprintf("COPY apache/httpd.conf %s/apache/httpd.conf", confRoot))
	b.checks = append(b.checks, fmt.Sprintf("RUN %s -t -f %s/apache/httpd.conf", su.Binary, confRoot))
	b.expose = webPort
	b.runtime = append(b.runtime, "STOPSIGNAL SIGWINCH")
	if !php {
		b.runtime = append(b.runtime, "CMD "+arr(b.webCmdArray()...))
	}
}

func renderApacheConf(o map[string]any, su Support, php bool) string {
	var b strings.Builder
	dir := su.Layout["moduleDir"]
	mod := func(name string) { fmt.Fprintf(&b, "LoadModule %s_module %s/mod_%s.so\n", name, dir, name) }
	b.WriteString("# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\n")
	fmt.Fprintf(&b, "ServerRoot \"%s/apache\"\nPidFile \"/tmp/httpd.pid\"\nDefaultRuntimeDir /tmp\nListen %d\n", confRoot, webPort)
	headers := headersOn(o)
	realIP := gs(o, "realIpMode") != "off" && gs(o, "realIpMode") != ""
	mods := []string{"mpm_event", "authn_core", "authz_core", "mime", "dir", "log_config", "unixd"}
	if len(headers) > 0 {
		mods = append(mods, "headers")
	}
	if gb(o, "gzip") {
		mods = append(mods, "filter", "deflate")
	}
	if realIP {
		mods = append(mods, "remoteip")
	}
	if php {
		mods = append(mods, "proxy", "proxy_fcgi")
	}
	for _, m := range mods {
		mod(m)
	}
	name := gs(o, "serverName")
	if name == "_" {
		name = "localhost"
	}
	tokens := "Prod"
	if gb(o, "serverTokens") {
		tokens = "Full"
	}
	fmt.Fprintf(&b, "ServerName %s\nServerTokens %s\nServerSignature Off\nTraceEnable Off\nTimeout 60\nKeepAlive On\nKeepAliveTimeout %v\n", name, tokens, o["keepaliveTimeout"])
	fmt.Fprintf(&b, "LimitRequestBody %d\nTypesConfig %s\nErrorLog /dev/stderr\nLogLevel warn\n", sizeBytes(gs(o, "clientMaxBodySize")), su.Layout["mimeTypes"])
	if realIP {
		hdr := "X-Forwarded-For"
		if gs(o, "realIpMode") == "x-real-ip" {
			hdr = "X-Real-IP"
		}
		fmt.Fprintf(&b, "RemoteIPHeader %s\n", hdr)
		for _, cidr := range cidrList(gs(o, "trustedProxies")) {
			fmt.Fprintf(&b, "RemoteIPInternalProxy %s\n", cidr)
		}
	}
	if gb(o, "accessLog") {
		b.WriteString("LogFormat \"%h %l %u %t \\\"%r\\\" %>s %b\" common\nCustomLog /dev/stdout common\n")
	}
	for _, h := range headers {
		fmt.Fprintf(&b, "Header always set %s \"%s\"\n", h[0], h[1])
	}
	if gb(o, "gzip") {
		fmt.Fprintf(&b, "AddOutputFilterByType DEFLATE %s\n", compressTypes)
	}
	root := gs(o, "documentRoot")
	fmt.Fprintf(&b, "DocumentRoot \"%s\"\n<Directory />\n    AllowOverride None\n    Require all denied\n</Directory>\n", root)
	fmt.Fprintf(&b, "<Directory \"%s\">\n    Options FollowSymLinks\n    AllowOverride None\n    Require all granted\n", root)
	if php {
		b.WriteString("    DirectoryIndex index.php index.html\n    FallbackResource /index.php\n")
	} else {
		b.WriteString("    DirectoryIndex index.html\n")
	}
	b.WriteString("</Directory>\n<LocationMatch \"/\\.(?!well-known)\">\n    Require all denied\n</LocationMatch>\n")
	if php {
		fmt.Fprintf(&b, "ProxyTimeout %v\n<FilesMatch \"\\.php$\">\n    SetHandler \"proxy:fcgi://127.0.0.1:%d\"\n</FilesMatch>\n", o["fastcgiReadTimeout"], fpmPort)
	}
	return b.String()
}

// ---------------------------------------------------------------- caddy

func (b *build) caddy() {
	o := b.sel["caddy"].Settings
	_, php := b.sel["php"]
	b.siteDirs(gs(o, "documentRoot"))
	b.readonly = append(b.readonly, confRoot+"/caddy")
	b.files = append(b.files, imagebuild.File{Path: "caddy/Caddyfile", Mode: 0o644, Content: renderCaddyfile(o, php)})
	b.copies = append(b.copies, fmt.Sprintf("COPY caddy/Caddyfile %s/caddy/Caddyfile", confRoot))
	b.env["XDG_CONFIG_HOME"] = "/tmp/caddy/config"
	b.env["XDG_DATA_HOME"] = "/tmp/caddy/data"
	b.checks = append(b.checks, fmt.Sprintf("RUN %s validate --config %s/caddy/Caddyfile --adapter caddyfile", b.sup["caddy"].Binary, confRoot))
	b.expose = webPort
	if !php {
		b.runtime = append(b.runtime, "CMD "+arr(b.webCmdArray()...))
	}
}

func renderCaddyfile(o map[string]any, php bool) string {
	var b strings.Builder
	b.WriteString("# Generated by cluster-manager (imagecompose). Change the recipe, not this file.\n{\n    admin off\n    auto_https off\n    persist_config off\n")
	if mode := gs(o, "realIpMode"); mode != "off" && mode != "" {
		hdr := "X-Forwarded-For"
		if mode == "x-real-ip" {
			hdr = "X-Real-IP"
		}
		fmt.Fprintf(&b, "    servers {\n        trusted_proxies static %s\n        client_ip_headers %s\n    }\n", strings.Join(cidrList(gs(o, "trustedProxies")), " "), hdr)
	}
	b.WriteString("}\n")
	addr := fmt.Sprintf(":%d", webPort)
	if n := gs(o, "serverName"); n != "_" {
		addr = fmt.Sprintf("http://%s:%d", n, webPort)
	}
	fmt.Fprintf(&b, "%s {\n    root * %s\n", addr, gs(o, "documentRoot"))
	if gb(o, "accessLog") {
		b.WriteString("    log {\n        output stdout\n    }\n")
	}
	fmt.Fprintf(&b, "    request_body {\n        max_size %d\n    }\n", sizeBytes(gs(o, "clientMaxBodySize")))
	if gb(o, "gzip") {
		b.WriteString("    encode gzip zstd\n")
	}
	b.WriteString("    header {\n        -Server\n")
	for _, h := range headersOn(o) {
		fmt.Fprintf(&b, "        %s \"%s\"\n", h[0], h[1])
	}
	b.WriteString("    }\n    @dotfiles {\n        path_regexp ^(.*/)?\\.\n        not path /.well-known/*\n    }\n    respond @dotfiles 404\n")
	if php {
		fmt.Fprintf(&b, "    php_fastcgi 127.0.0.1:%d {\n        read_timeout %vs\n    }\n", fpmPort, o["fastcgiReadTimeout"])
	}
	b.WriteString("    file_server\n}\n")
	return b.String()
}
