package imagebuild

import (
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"
)

// File is one file of the build context. Path is relative and slash
// separated; Mode is 0644 or 0755.
type File struct {
	Path    string `json:"path"`
	Mode    uint32 `json:"mode"`
	Content string `json:"content"`
}

// Rendered is the deterministic output for one spec: Dockerfile content and
// context files in sorted path order, plus content hashes. Identical specs
// give identical Rendered values; no timestamps or random values enter it.
type Rendered struct {
	SpecHash    string `json:"specHash"`
	ContextHash string `json:"contextHash"`
	Dockerfile  string `json:"dockerfile"`
	// Files holds the context files without the Dockerfile.
	Files []File `json:"files"`
	// BaseImage is the pinned base reference used in the Dockerfile.
	BaseImage string `json:"baseImage"`
}

// BaseReference returns the pinned base image reference of a spec.
func BaseReference(s WebServerSpec) string {
	n := s.Normalize()
	return "docker.io/library/nginx:" + n.Nginx.Version + "-alpine@" + n.Nginx.BaseDigest
}

// Render validates and renders the spec. Validation uses the catalog; nil
// selects the default catalog.
func Render(s WebServerSpec, c *Catalog) (Rendered, error) {
	if c == nil {
		c = DefaultCatalog()
	}
	if err := s.Validate(c); err != nil {
		return Rendered{}, err
	}
	n := s.Normalize()
	r := Rendered{SpecHash: s.Hash(), BaseImage: BaseReference(n)}
	hasPHP := n.PHP.Version != ""

	files := []File{
		{Path: "nginx/nginx.conf", Mode: 0o644, Content: renderNginxConf(n.Nginx.Options)},
		{Path: "nginx/default.conf", Mode: 0o644, Content: renderServerConf(n, hasPHP)},
	}
	if n.Nginx.CustomSnippet != "" {
		files = append(files, File{Path: "nginx/custom.conf", Mode: 0o644, Content: n.Nginx.CustomSnippet + "\n"})
	}
	if hasPHP {
		files = append(files,
			File{Path: "php/dbcm.ini", Mode: 0o644, Content: renderINI(n.PHP.INI)},
			File{Path: "php/dbcm-pool.conf", Mode: 0o644, Content: "[www]\nlisten = 127.0.0.1:9000\n"},
			File{Path: "docker-entrypoint.d/40-php-fpm.sh", Mode: 0o755,
				Content: "#!/bin/sh\nset -eu\nphp-fpm" + strings.ReplaceAll(n.PHP.Version, ".", "") + " -D\n"},
		)
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	r.Files = files
	r.Dockerfile = renderDockerfile(n, r)
	r.ContextHash = contextHash(r)
	return r, nil
}

func boolOnOff(b *bool) string {
	if b != nil && *b {
		return "on"
	}
	return "off"
}

func renderNginxConf(o NginxOptions) string {
	var b strings.Builder
	b.WriteString("# Generated by DB Cluster Manager. Do not edit; change the composition instead.\n")
	b.WriteString("user nginx;\n")
	fmt.Fprintf(&b, "worker_processes %s;\n", o.WorkerProcesses)
	b.WriteString("error_log /dev/stderr warn;\npid /run/nginx.pid;\n\n")
	fmt.Fprintf(&b, "events {\n    worker_connections %d;\n}\n\n", o.WorkerConnections)
	b.WriteString("http {\n")
	b.WriteString("    include /etc/nginx/mime.types;\n    default_type application/octet-stream;\n")
	b.WriteString("    access_log /dev/stdout;\n    sendfile on;\n")
	fmt.Fprintf(&b, "    keepalive_timeout %d;\n", o.KeepaliveTimeout)
	fmt.Fprintf(&b, "    server_tokens %s;\n", boolOnOff(o.ServerTokens))
	fmt.Fprintf(&b, "    client_max_body_size %s;\n", o.ClientMaxBodySize)
	fmt.Fprintf(&b, "    gzip %s;\n", boolOnOff(o.Gzip))
	b.WriteString("    include /etc/nginx/conf.d/*.conf;\n}\n")
	return b.String()
}

func renderServerConf(n WebServerSpec, hasPHP bool) string {
	o := n.Nginx.Options
	var b strings.Builder
	b.WriteString("# Generated by DB Cluster Manager. Do not edit; change the composition instead.\n")
	b.WriteString("server {\n    listen 80;\n")
	fmt.Fprintf(&b, "    server_name %s;\n    root %s;\n", o.ServerName, o.DocumentRoot)
	if hasPHP {
		b.WriteString("    index index.php index.html;\n")
	} else {
		b.WriteString("    index index.html;\n")
	}
	if o.SecurityHeaders != nil && *o.SecurityHeaders {
		b.WriteString("    add_header X-Content-Type-Options \"nosniff\" always;\n")
		b.WriteString("    add_header X-Frame-Options \"SAMEORIGIN\" always;\n")
		b.WriteString("    add_header Referrer-Policy \"strict-origin-when-cross-origin\" always;\n")
	}
	b.WriteString("\n    location ~ /\\.(?!well-known) {\n        deny all;\n    }\n\n")
	if hasPHP {
		b.WriteString("    location / {\n        try_files $uri $uri/ /index.php?$query_string;\n    }\n\n")
		b.WriteString("    location ~ \\.php$ {\n")
		b.WriteString("        include /etc/nginx/fastcgi_params;\n")
		b.WriteString("        fastcgi_split_path_info ^(.+\\.php)(/.+)$;\n")
		b.WriteString("        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;\n")
		fmt.Fprintf(&b, "        fastcgi_read_timeout %ds;\n", o.FastCGIReadTimeout)
		b.WriteString("        fastcgi_pass 127.0.0.1:9000;\n    }\n")
	} else {
		b.WriteString("    location / {\n        try_files $uri $uri/ =404;\n    }\n")
	}
	if n.Nginx.CustomSnippet != "" {
		b.WriteString("\n    include /etc/nginx/snippets/dbcm-custom.conf;\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func renderINI(ini map[string]string) string {
	keys := make([]string, 0, len(ini))
	for k := range ini {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("; Generated by DB Cluster Manager. Do not edit; change the composition instead.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s = %s\n", k, iniValue(ini[k]))
	}
	return b.String()
}

// iniValue quotes values that contain characters special to the ini parser.
func iniValue(v string) string {
	if strings.ContainsAny(v, " &~|^!()=") {
		return `"` + v + `"`
	}
	return v
}

func renderDockerfile(n WebServerSpec, r Rendered) string {
	var b strings.Builder
	b.WriteString("# syntax=docker/dockerfile:1\n")
	b.WriteString("# Generated by DB Cluster Manager (imagebuild). Review before building.\n")
	fmt.Fprintf(&b, "FROM %s\n", r.BaseImage)
	fmt.Fprintf(&b, "LABEL org.opencontainers.image.title=%q \\\n      org.opencontainers.image.base.digest=%q \\\n      dbcm.spec-hash=%q\n",
		n.Name, n.Nginx.BaseDigest, r.SpecHash)

	pkgs := append([]string(nil), n.ExtraPackages...)
	if v := n.PHP.Version; v != "" {
		p := phpPkg(v)
		pkgs = append(pkgs, p+"-fpm")
		for _, e := range n.PHP.Extensions {
			pkgs = append(pkgs, p+"-"+e)
		}
	}
	sort.Strings(pkgs)
	if len(pkgs) > 0 {
		b.WriteString("RUN apk add --no-cache \\\n")
		for i, p := range pkgs {
			if i < len(pkgs)-1 {
				fmt.Fprintf(&b, "      %s \\\n", p)
			} else {
				fmt.Fprintf(&b, "      %s\n", p)
			}
		}
	}
	b.WriteString("COPY nginx/nginx.conf /etc/nginx/nginx.conf\n")
	b.WriteString("COPY nginx/default.conf /etc/nginx/conf.d/default.conf\n")
	if n.Nginx.CustomSnippet != "" {
		b.WriteString("COPY nginx/custom.conf /etc/nginx/snippets/dbcm-custom.conf\n")
	}
	if v := n.PHP.Version; v != "" {
		p := phpPkg(v)
		fmt.Fprintf(&b, "COPY php/dbcm.ini /etc/%s/conf.d/99-dbcm.ini\n", p)
		fmt.Fprintf(&b, "COPY php/dbcm-pool.conf /etc/%s/php-fpm.d/zz-dbcm.conf\n", p)
		b.WriteString("COPY docker-entrypoint.d/40-php-fpm.sh /docker-entrypoint.d/40-php-fpm.sh\n")
		fmt.Fprintf(&b, "RUN php-fpm%s -t && nginx -t\n", strings.ReplaceAll(v, ".", ""))
	} else {
		b.WriteString("RUN nginx -t\n")
	}
	b.WriteString("EXPOSE 80\n")
	return b.String()
}

// contextHash hashes the Dockerfile and all files in sorted order with
// length prefixes, so no two different contexts collide by concatenation.
func contextHash(r Rendered) string {
	h := sha256.New()
	put := func(path string, mode uint32, content string) {
		var n [8]byte
		for _, s := range []string{path, content} {
			binary.BigEndian.PutUint64(n[:], uint64(len(s)))
			h.Write(n[:])
			h.Write([]byte(s))
		}
		binary.BigEndian.PutUint64(n[:], uint64(mode))
		h.Write(n[:])
	}
	put("Dockerfile", 0o644, r.Dockerfile)
	for _, f := range r.Files {
		put(f.Path, f.Mode, f.Content)
	}
	return "sha256:" + hex.EncodeToString(h.Sum(nil))
}
